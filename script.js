let yourTrade = [];
let theirTrade = [];

const grid = document.getElementById("itemsGrid");
const search = document.getElementById("search");
const filter = document.getElementById("filter");

function renderItems() {
  const q = search.value.toLowerCase();
  const f = filter.value;

  const filtered = items.filter(item => {
    const matchesSearch =
      item.name.toLowerCase().includes(q) ||
      item.category.toLowerCase().includes(q) ||
      item.status.toLowerCase().includes(q);

    const matchesFilter =
      f === "All" || item.category === f;

    return matchesSearch && matchesFilter;
  });

  grid.innerHTML = filtered.map(item => `
    <div class="card">

      <div class="icon">
        ${item.icon}
      </div>

      <div class="item-name">
        ${item.name}
      </div>

      <span class="category">
        ${item.category}
      </span>

      <div class="value">
        ${item.value}
      </div>

      <div class="mini">
        Demand: ${item.demand}<br>
        Status: ${item.status}
      </div>

      <div class="add-row">
        <button onclick="quickAdd('${item.name}','your')">
          Your Side
        </button>

        <button onclick="quickAdd('${item.name}','their')">
          Their Side
        </button>
      </div>

    </div>
  `).join("");
}

function fillSelects() {

  const options = items.map(item => `
    <option value="${item.name}">
      ${item.icon} ${item.name} — ${item.value}
    </option>
  `).join("");

  document.getElementById("yourSelect").innerHTML = options;
  document.getElementById("theirSelect").innerHTML = options;
}

function showBoard() {
  document.getElementById("homePage").classList.add("hidden");
  document.getElementById("boardPage").classList.remove("hidden");
}

function showHome() {
  document.getElementById("boardPage").classList.add("hidden");
  document.getElementById("homePage").classList.remove("hidden");
}

function getItem(name) {
  return items.find(item => item.name === name);
}

function quickAdd(name, side) {

  const item = getItem(name);

  if(side === "your") {
    yourTrade.push(item);
  }

  if(side === "their") {
    theirTrade.push(item);
  }

  updateTradeBoard();
  showBoard();
}

function addTradeItem(side) {

  const select =
    side === "your"
      ? document.getElementById("yourSelect")
      : document.getElementById("theirSelect");

  const item = getItem(select.value);

  if(side === "your") {
    yourTrade.push(item);
  }

  if(side === "their") {
    theirTrade.push(item);
  }

  updateTradeBoard();
}

function removeTradeItem(side, index) {

  if(side === "your") {
    yourTrade.splice(index, 1);
  }

  if(side === "their") {
    theirTrade.splice(index, 1);
  }

  updateTradeBoard();
}

function total(list) {

  return Number(
    list.reduce((sum, item) => sum + item.value, 0).toFixed(2)
  );
}

function renderTradeList(list, side) {

  return list.map((item, index) => `
    <div class="trade-item">

      <span>
        ${item.icon}
        <b>${item.name}</b><br>

        <small>
          ${item.category} • ${item.value}
        </small>
      </span>

      <button
        class="remove"
        onclick="removeTradeItem('${side}', ${index})"
      >
        ✕
      </button>

    </div>
  `).join("");
}

function updateTradeBoard() {

  const yourTotal = total(yourTrade);
  const theirTotal = total(theirTrade);

  document.getElementById("yourList").innerHTML =
    renderTradeList(yourTrade, "your");

  document.getElementById("theirList").innerHTML =
    renderTradeList(theirTrade, "their");

  document.getElementById("yourTotal").textContent =
    yourTotal;

  document.getElementById("theirTotal").textContent =
    theirTotal;

  const diff =
    Number((theirTotal - yourTotal).toFixed(2));

  let result = "Add items 💖";

  if(diff <= -2){
    result = "SCAMMED 💀";
  }
  else if(diff <= -1){
    result = "MEGA LOSE 😭";
  }
  else if(diff <= -0.5){
    result = "BIG LOSE 😬";
  }
  else if(diff <= -0.15){
    result = "LOSE 🥲";
  }
  else if(diff < 0.15){
    result = "FAIR 💕";
  }
  else if(diff < 0.5){
    result = "WIN ✨";
  }
  else if(diff < 1){
    result = "BIG WIN 😍";
  }
  else{
    result = "MEGA WIN 👑";
  }

  document.getElementById("tradeResult").textContent =
    result;
}

